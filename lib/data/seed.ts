export function utilisation(seed: number, cpu: number | null, memory: number | null) {
  return Array.from({ length: 30 }, (_, i) => {
    const date = new Date(TODAY)
    date.setUTCDate(date.getUTCDate() - (29 - i))
    const wave = Math.sin(i * 0.7 + seed) * 6 + Math.sin(i * 2.3 + seed * 2) * 3
    const clamp = (v: number) => Math.max(0, Math.min(100, Math.round(v)))
    return {
      day: date.toISOString().slice(5, 10),
      cpu: cpu === null ? 0 : clamp(cpu + wave),
      memory: memory === null ? 0 : clamp(memory + wave * 0.6),
    }
  })
}

